<?php

declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $definition->rootNode()
        ->children()
            ->arrayNode('resources')
                ->info('#[ScimResource] classes beside the autoconfigured services, for a services.yaml that excludes the entities.')
                ->stringPrototype()->cannotBeEmpty()->end()
            ->end()
            ->arrayNode('access_tokens')
                ->info('Static bearer tokens, keyed by client name. The client name is the user identifier.')
                ->useAttributeAsKey('client')
                ->normalizeKeys(false)
                ->scalarPrototype()->cannotBeEmpty()->end()
            ->end()
            ->integerNode('max_results')
                ->info('Largest page size; published as filter.maxResults.')
                ->min(1)
                ->defaultValue(200)
            ->end()
            ->arrayNode('bulk')
                ->info('Published as bulk; enabled: false turns /Bulk off.')
                ->canBeDisabled()
                ->children()
                    ->integerNode('max_operations')->min(1)->defaultValue(1000)->end()
                    ->integerNode('max_payload_size_bytes')->min(1)->defaultValue(1048576)->end()
                ->end()
            ->end()
            ->arrayNode('rate_limit')
                ->info('A token bucket per client after the firewall. Over the limit: 429 with Retry-After.')
                ->canBeEnabled()
                ->children()
                    ->integerNode('limit')->info('Bucket size, the largest burst.')->min(1)->defaultValue(500)->end()
                    ->arrayNode('rate')
                        ->info('Refill.')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->stringNode('interval')->cannotBeEmpty()->defaultValue('1 second')->end()
                            ->integerNode('amount')->min(1)->defaultValue(50)->end()
                        ->end()
                    ->end()
                    ->stringNode('cache_pool')->info('A shared pool, for example Redis, when several servers share the limit.')->cannotBeEmpty()->defaultValue('cache.rate_limiter')->end()
                    ->stringNode('limiter')->info('Service id of a RateLimiterFactoryInterface. It replaces limit, rate and cache_pool.')->cannotBeEmpty()->defaultNull()->end()
                ->end()
            ->end()
            ->arrayNode('me')
                ->info('The /Me alias (RFC 7644 section 3.11). Disabled: 501.')
                ->canBeEnabled()
                ->children()
                    ->stringNode('resource_type')->cannotBeEmpty()->defaultValue('User')->end()
                    ->stringNode('attribute')->info('The SCIM attribute that equals the user identifier of the security token.')->cannotBeEmpty()->defaultValue('userName')->end()
                    ->stringNode('resolver')->info('Service id of a MeResolver. It replaces resource_type and attribute.')->cannotBeEmpty()->defaultNull()->end()
                ->end()
            ->end()
            ->arrayNode('pagination')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('cursor')
                        ->info('RFC 9865 cursors (?cursor). Disabled: the cursor parameter is ignored.')
                        ->canBeDisabled()
                        ->children()
                            ->stringNode('key')->info('Encrypts the cursors. Each server needs the same key. A new key invalidates every cursor. Empty from an environment variable: each SCIM request fails.')->cannotBeEmpty()->defaultValue('%kernel.secret%')->end()
                            ->integerNode('timeout_seconds')->info('Published as cursorTimeout. Null: cursors do not expire.')->min(1)->defaultNull()->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;
};
